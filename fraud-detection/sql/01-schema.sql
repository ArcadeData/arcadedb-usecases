-- Vertex types
CREATE VERTEX TYPE Account IF NOT EXISTS;
CREATE PROPERTY Account.id IF NOT EXISTS STRING;
CREATE PROPERTY Account.name IF NOT EXISTS STRING;
CREATE PROPERTY Account.full_name IF NOT EXISTS STRING;
CREATE PROPERTY Account.ssn IF NOT EXISTS STRING;
CREATE PROPERTY Account.credit_limit IF NOT EXISTS FLOAT;
CREATE PROPERTY Account.balance IF NOT EXISTS FLOAT;
CREATE VERTEX TYPE Customer IF NOT EXISTS;
CREATE PROPERTY Customer.id IF NOT EXISTS STRING;
CREATE PROPERTY Customer.baseline_behavior IF NOT EXISTS STRING;
CREATE PROPERTY Customer.recent_behavior IF NOT EXISTS STRING;
CREATE PROPERTY Customer.profile_embedding IF NOT EXISTS LIST;
CREATE VERTEX TYPE Device IF NOT EXISTS;
CREATE PROPERTY Device.id IF NOT EXISTS STRING;
CREATE PROPERTY Device.fingerprint IF NOT EXISTS STRING;
CREATE VERTEX TYPE Phone IF NOT EXISTS;
CREATE PROPERTY Phone.number IF NOT EXISTS STRING;
CREATE VERTEX TYPE Address IF NOT EXISTS;
CREATE PROPERTY Address.street IF NOT EXISTS STRING;
CREATE PROPERTY Address.city IF NOT EXISTS STRING;
CREATE PROPERTY Address.zip IF NOT EXISTS STRING;
CREATE VERTEX TYPE Email IF NOT EXISTS;
CREATE PROPERTY Email.address IF NOT EXISTS STRING;
CREATE VERTEX TYPE Beneficiary IF NOT EXISTS;
CREATE PROPERTY Beneficiary.id IF NOT EXISTS STRING;
CREATE PROPERTY Beneficiary.name IF NOT EXISTS STRING;
CREATE VERTEX TYPE Transaction IF NOT EXISTS;
CREATE PROPERTY Transaction.id IF NOT EXISTS STRING;
CREATE PROPERTY Transaction.amount IF NOT EXISTS FLOAT;
CREATE PROPERTY Transaction.merchant IF NOT EXISTS STRING;
CREATE PROPERTY Transaction.behavior_embedding IF NOT EXISTS LIST;
CREATE PROPERTY Transaction.ts IF NOT EXISTS DATETIME;
CREATE PROPERTY Transaction.account_id IF NOT EXISTS STRING;
-- Edge types
CREATE EDGE TYPE USES_DEVICE IF NOT EXISTS;
CREATE EDGE TYPE HAS_PHONE IF NOT EXISTS;
CREATE EDGE TYPE HAS_ADDRESS IF NOT EXISTS;
CREATE EDGE TYPE HAS_EMAIL IF NOT EXISTS;
CREATE EDGE TYPE TRANSFERRED_TO IF NOT EXISTS;
CREATE PROPERTY TRANSFERRED_TO.amount IF NOT EXISTS FLOAT;
CREATE PROPERTY TRANSFERRED_TO.ts IF NOT EXISTS DATETIME;
CREATE EDGE TYPE BENEFICIARY_OF IF NOT EXISTS;
-- Document types
CREATE DOCUMENT TYPE Deposit IF NOT EXISTS;
CREATE PROPERTY Deposit.account_id IF NOT EXISTS STRING;
CREATE PROPERTY Deposit.amount IF NOT EXISTS FLOAT;
CREATE PROPERTY Deposit.ts IF NOT EXISTS DATETIME;
-- Indexes
CREATE INDEX IF NOT EXISTS ON Account (id) UNIQUE;
CREATE INDEX IF NOT EXISTS ON Customer (id) UNIQUE;
CREATE INDEX IF NOT EXISTS ON Transaction (id) UNIQUE;
CREATE INDEX IF NOT EXISTS ON Customer (profile_embedding) LSM_VECTOR METADATA { dimensions: 8, similarity: 'COSINE' };
CREATE INDEX IF NOT EXISTS ON Transaction (behavior_embedding) LSM_VECTOR METADATA { dimensions: 8, similarity: 'COSINE' };
